//! Транспайлер YoptaScript → JavaScript.
//!
//! Границы возможностей заданы намеренно и это НЕ полный паритет со стандартной библиотекой:
//!
//! * синтаксис — поддержан целиком: каждый узел AST печатается как эквивалентная
//!   конструкция современного JS (классы, генераторы, async/await, деструктуризация,
//!   опциональные цепочки, шаблонные строки, `using`, модули);
//! * свободные встроенные функции (`сказать`, `длина`, `тип`, таймеры и т.д.) —
//!   переписываются в нативные аналоги JS либо в крошечные хелперы `__yps*`,
//!   которые добавляются в начало вывода только если реально использованы;
//! * чисто статические пространства имён `Матан`, `Жсон`, `Отражение` — поддержаны
//!   только в точечной форме (`Матан.ПИ`, `Жсон.вСтроку(...)`, `Отражение.получить(...)`),
//!   которая переписывается 1:1 в `Math`/`JSON`/`Reflect`. Само имя как значение
//!   (`гыы м = Матан;`) остаётся ошибкой, неизвестный член (`Матан.пи`) — тоже, но с
//!   отдельной диагностикой, которая винит именно член, а не пространство имён.
//!   Два метода `Матан` переписываются не в нативный `Math`, а в хелперы, потому что
//!   нативная семантика расходится с интерпретатором: `округлить` → `__ypsRound`
//!   (JS округляет половины к +бесконечности, `f64::round` — от нуля) и `гипотенуза`
//!   → `__ypsHypot` (`Math.hypot` защищён от переполнения, интерпретатор считает
//!   наивный `sqrt(Σxᵢ²)`). Трансцендентные методы (`лог`, `синус`, `эксп`, ...)
//!   переписываются в нативные и могут отличаться от интерпретатора на единицы ULP:
//!   Rust считает их через libm, node — через V8. Это осознанно не чинится;
//! * остальные глобальные объекты стандартной библиотеки (`Кент`, `Помойка`, `Карта`,
//!   `Симбол`, типизированные массивы и прочие) и русскоязычные методы объектов
//!   (`объект.метод(...)`) — НЕ поддержаны. Ссылка на такой глобал даёт
//!   [`TranspileError`] с именем и позицией, а не молча сломанный JS.
//!
//! Различить пользовательский метод и метод стандартной библиотеки без системы типов
//! невозможно, поэтому выбрана явная ошибка вместо тихой неправильности.

mod builtins;
mod printer;
mod scope;

use std::fmt;

use yps_lexer::Span;
use yps_parser::Program;

pub use printer::print_program;

/// Ошибка транспиляции: программа синтаксически корректна, но использует
/// конструкцию, для которой у транспайлера нет безопасного JS-эквивалента.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TranspileError {
    pub message: String,
    pub span: Span,
}

impl fmt::Display for TranspileError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.message)
    }
}

impl std::error::Error for TranspileError {}

/// Транспилировать разобранную программу в исходный текст JavaScript.
///
/// # Errors
/// Возвращает [`TranspileError`], если программа обращается к неподдерживаемому
/// глобалу стандартной библиотеки или использует встроенную функцию неверно.
pub fn transpile(program: &Program) -> Result<String, TranspileError> {
    print_program(program)
}
