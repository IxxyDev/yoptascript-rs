'use strict';
function лог(метод, контекст) {
    const имя = контекст.имя;
    return (...аргс) => {
        console.log("[" + имя + "] вызов");
        const результат = метод(аргс[0], аргс[1]);
        console.log("[" + имя + "] результат: " + результат);
        return результат;
    };
}

class Калькулятор {
    сложить(а, б) {
        return а + б;
    }

    умножить(а, б) {
        return а * б;
    }
}
for (const имя of ["сложить", "умножить"]) {
    Калькулятор.prototype[имя] = лог(Калькулятор.prototype[имя], { имя });
}

const к = new Калькулятор();
к.сложить(2, 3);
к.умножить(4, 5);
