'use strict';
function подсветить(строки, ...значения) {
    let итог = "";
    for (let и = 0; и < строки.length; и += 1) {
        итог += строки[и];
        if (и < значения.length) {
            итог += "[" + значения[и] + "]";
        }
    }
    return итог;
}

const товар = "кофе";
const цена = 200;
console.log(подсветить`Заказ: ${товар} за ${цена} руб.`);

