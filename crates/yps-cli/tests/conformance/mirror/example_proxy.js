'use strict';
const защищённый = new Proxy(
  { баланс: 100 },
  {
    get: (цель, ключ, посредник) => {
      if (ключ in цель) {
        return цель[ключ];
      }
      return "нет такого поля: " + ключ;
    },
    set: (цель, ключ, значение, посредник) => {
      if (ключ === "баланс" && значение < 0) {
        throw "баланс не может быть отрицательным";
      }
      цель[ключ] = значение;
      return true;
    },
    has: (цель, ключ) => ключ in цель
  }
);

console.log(защищённый.баланс);
console.log(защищённый.секрет);

защищённый.баланс = 250;
console.log(защищённый.баланс);

console.log("баланс" in защищённый);
console.log("пароль" in защищённый);

try {
  защищённый.баланс = -5;
} catch (е) {
  console.log("поймали: " + е);
}

const логирующий = new Proxy(
  (а, б) => а + б,
  { apply: (цель, этот, аргументы) => {
      console.log("вызов с " + аргументы[0] + ", " + аргументы[1]);
      return цель(аргументы[0], аргументы[1]);
  } }
);
console.log(логирующий(7, 8));
